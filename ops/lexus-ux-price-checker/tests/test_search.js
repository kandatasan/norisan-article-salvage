const fs=require('fs'), vm=require('vm'), assert=require('assert');
const path=require('path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/reference_price_bands.json'),'utf8'));
const match=html.match(/function matchingBand\([^]*?\n\}(?=\nfunction render\(\))/);
assert(match,'Could not isolate matchingBand');
const sandbox={bands:data.cohorts};
vm.createContext(sandbox);
vm.runInContext(match[0],sandbox);
const find=(model,grade,year,mileage,seg)=>sandbox.matchingBand(model,grade,year,mileage,seg);
// Concrete grade values are backed by grade-matched observations, never pooled data.
assert.equal(find('200','fs','2019','any','general_market').grade,'fs');
assert.equal(find('200','fs','2019','any','general_market').median_man,295.5);
assert.equal(find('200','base','2019','any','general_market'),undefined);
assert.equal(find('200','all','2019','any','general_market').grade,'all');
assert.equal(find('250h','c','2021','any','general_market').median_man,353);
assert.equal(find('250h','fs','2021','any','general_market').median_man,379.9);
assert.equal(find('250h','fs','2021','any','general_market').sample_size,5);
assert.equal(find('250h','base','2021','any','general_market'),undefined);
assert.equal(find('250h','all','2021','any','general_market').grade,'all');
assert.equal(find('250h','all','2021','any','general_market').median_man,371.7);
assert.equal(find('250h','fs','2022','any','general_market'),undefined);
const pooled=find('250h','all','2022','any','general_market');
assert.equal(pooled.grade,'all');
assert.equal(pooled.observed_years[0],2019);
assert.equal(pooled.observed_years[1],2023);
assert.equal(find('300h','fs','2024','any','lexus_cpo').median_man,511.9);
assert.equal(find('300h','fs','2024','any','lexus_cpo').sample_size,7);
assert.equal(find('300h','l','2024','any','lexus_cpo').median_man,485.4);
assert.equal(find('300h','base','2024','any','lexus_cpo'),undefined);
assert.equal(find('300h','fs','2024','any','general_market'),undefined);
assert.equal(find('300h','all','2024','any','general_market').grade,'all');
assert.equal(find('300h','all','2024','any','lexus_cpo').grade,'all');
assert(!find('300h','all','2025','any','general_market'),'Do not fabricate general market 2025 UX300h from 2024 data');
assert(!find('300e','all','2025','any','general_market'),'Do not substitute unrelated UX300e years');
assert(!html.includes('id="color"'));
assert(!html.includes('カラー未反映'));
assert(html.includes('複数年式の参考値'));
console.log('UX_GENERAL_USED_MATCHING_TEST=PASS');
