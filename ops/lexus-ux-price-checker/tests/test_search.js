const fs=require('fs'), vm=require('vm'), assert=require('assert');
const path=require('path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/reference_price_bands.json'),'utf8'));
const match=html.match(/function matchingBand\([^]*?\n\}(?=\nfunction render\(\))/);
assert(match,'Could not isolate matchingBand');
const sandbox={bands:data.cohorts};
vm.createContext(sandbox);
vm.runInContext(match[0],sandbox);
const find=(model,grade,year,mileage,seg)=>sandbox.matchingBand(model,grade,year,mileage,seg);
assert.equal(find('200','fs','2019','any','general_market').year,2019);
assert.equal(find('250h','c','2021','any','general_market').grade,'c');
const multiYear=find('250h','fs','2022','any','general_market');
assert(multiYear,'General-market UX250h should have a qualified model-level fallback');
assert.equal(multiYear.grade,'all');
assert.equal(multiYear.year,'any');
assert.equal(multiYear.observed_years[0],2019);
assert.equal(multiYear.observed_years[1],2023);
assert(find('300h','all','2024','any','general_market'));
assert(find('300h','all','2024','any','lexus_cpo'));
assert(!find('300h','all','2025','any','general_market'),'Do not fabricate general market 2025 UX300h from 2024 data');
assert(!find('300e','all','2025','any','general_market'),'Do not substitute unrelated UX300e years');
assert(!html.includes('id="color"'));
assert(!html.includes('カラー未反映'));
assert(html.includes('複数年式の参考値'));
console.log('UX_GENERAL_USED_MATCHING_TEST=PASS');
