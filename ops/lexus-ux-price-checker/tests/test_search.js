const fs=require('fs'), vm=require('vm'), assert=require('assert');
const path=require('path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/reference_price_bands.json'),'utf8'));
const match=html.match(/function matchingBand\([^]*?\n\}(?=\nfunction render\(\))/);
assert(match,'Could not isolate matchingBand');
const sandbox={bands:data.cohorts};
vm.createContext(sandbox);
vm.runInContext(match[0],sandbox);
const find=(model,grade,year,mileage,seg)=>sandbox.matchingBand(model,grade,year,mileage,seg);
assert.equal(data.cohorts.length,10);
assert(data.cohorts.every(b=>b.grade!=='all'),'Mixed-grade cohorts must not be public');
assert(!html.includes("['all','全グレード'"),'Remove all-grade options');
assert(!html.includes('全グレード'),'No pooled-grade labels anywhere in the tool');
assert(html.includes("pGrade==='all'"),'Legacy iframe grade=all should map to valid specific grade');
assert(html.includes("const defaultGrades="));
assert.equal(find('250h','all','2021','any','general_market'),undefined);
assert.equal(find('250h','c','2019','any','general_market').median_man,302.9);
assert.equal(find('250h','c','2019','any','general_market').sample_size,7);
assert.equal(find('250h','c','2020','any','general_market').median_man,315.9);
assert.equal(find('250h','c','2020','any','general_market').sample_size,5);
assert.equal(find('250h','c','2021','any','general_market').median_man,353);
assert.equal(find('250h','fs','2019','any','general_market').median_man,355.2);
assert.equal(find('250h','fs','2021','any','general_market').median_man,379.9);
assert.equal(find('250h','base','2019','any','general_market'),undefined);
assert.equal(find('250h','base','2021','any','general_market'),undefined);
assert.equal(find('250h','fs','2020','any','general_market'),undefined);
assert.equal(find('250h','graceful','2023','any','lexus_cpo').median_man,433.8);
assert.equal(find('250h','graceful','2023','any','general_market'),undefined);
assert.equal(find('300h','fs','2024','any','lexus_cpo').median_man,511.9);
assert.equal(find('300h','l','2024','any','lexus_cpo').median_man,485.4);
assert.equal(find('300h','base','2024','any','lexus_cpo'),undefined);
assert.equal(find('300h','all','2024','any','lexus_cpo'),undefined);
assert.equal(find('300e','l','2021','any','general_market').median_man,287.8);
assert.equal(find('300e','l','2025','any','general_market'),undefined);
assert.equal(find('300h','c','2025','any','lexus_cpo'),undefined);
assert(!html.includes('id="color"'));
assert(!html.includes('カラー未反映'));
console.log('UX_GRADE_ONLY_MATCHING_TEST=PASS');
