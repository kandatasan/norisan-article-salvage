const fs=require('fs'),vm=require('vm'),assert=require('assert');
const path=require('path'),root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/reference_price_bands.json'),'utf8'));
assert(!html.includes('全グレード'));
assert(!data.cohorts.some(c=>c.grade==='all'));
assert(html.includes('type="range" id="year"')&&html.includes('type="range" id="km"'));
assert(html.includes('id="general-price"')&&html.includes('id="cpo-price"'));
assert(!html.includes('id="price-range"'));
assert(!html.includes('px.a8.net')&&!html.includes('ガリバー'));
const m=html.match(/function estimate\([^]*?\n\}(?=\nfunction render\(\))/);
assert(m,'separate-market estimator missing');
const ctx={clamp:(v,min,max)=>Math.max(min,Math.min(max,v))};vm.createContext(ctx);vm.runInContext(m[0],ctx);
const est=(model,trim,y,km,segment)=>ctx.estimate(model,trim,y,km,data.cohorts,segment);
const general=est('250h','c',2020,30000,'general_market');
const cpo=est('250h','c',2020,30000,'lexus_cpo');
assert(general&&general.gradeMatched&&cpo&&cpo.gradeMatched);
assert.notEqual(general.low,cpo.low,'general/CPO must stay independent');
assert(est('250h','c',2022,30000,'general_market').low>general.low,'year slider');
assert(est('250h','c',2020,90000,'general_market').high<est('250h','c',2020,10000,'general_market').high,'mileage slider');
assert(est('250h','emotional',2023,30000,'general_market')&&!est('250h','emotional',2023,30000,'general_market').gradeMatched);
assert(est('250h','emotional',2023,30000,'lexus_cpo')&&!est('250h','emotional',2023,30000,'lexus_cpo').gradeMatched);
assert(est('300h','l',2024,30000,'lexus_cpo')&&est('300h','l',2024,30000,'lexus_cpo').gradeMatched);
assert.equal(est('300h','l',2024,30000,'general_market'),null);
assert.equal(est('200','fs',2019,30000,'lexus_cpo'),null);
assert.equal(est('300e','l',2021,30000,'lexus_cpo'),null);
assert(est('200','base',2019,30000,'general_market')&&!est('200','base',2019,30000,'general_market').gradeMatched);
assert(est('300e','l',2021,30000,'general_market'));
console.log('UX_SIMPLE_TWO_MARKETS=PASS; verified_cohorts='+data.cohorts.length);
