const fs=require('fs'),vm=require('vm'),assert=require('assert');
const path=require('path'),root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const json=JSON.parse(fs.readFileSync(path.join(root,'data/reference_price_bands.json'),'utf8'));
assert(!html.includes("'all','全グレード'")&&!html.includes('全グレード'));
assert(!json.cohorts.some(x=>x.grade==='all'));
const m=html.match(/function matchingBand\([^]*?\n\}(?=\nfunction render\(\))/);
assert(m,'Matcher function missing');
const context={bands:json.cohorts};vm.createContext(context);vm.runInContext(m[0],context);
const f=(model,grade,year,seg)=>context.matchingBand(model,grade,String(year),'any',seg);
assert.equal(f('250h','all',2020,'general_market'),undefined);
assert.equal(f('250h','all',2021,'general_market'),undefined);
assert.equal(f('300h','all',2024,'lexus_cpo'),undefined);
assert.equal(f('250h','base',2020,'general_market'),undefined);
assert.equal(f('250h','fs',2020,'general_market'),undefined);
assert.equal(f('250h','fs',2019,'general_market').median_man,355.2);
assert.equal(f('250h','fs',2021,'general_market').median_man,379.9);
assert.equal(f('250h','c',2020,'general_market').sample_size,7);
assert.equal(f('250h','c',2020,'general_market').lower_man,280);
assert.equal(f('250h','c',2020,'general_market').upper_man,340);
assert.equal(f('250h','c',2020,'lexus_cpo').sample_size,6);
assert.equal(f('250h','c',2020,'lexus_cpo').lower_man,310);
assert.equal(f('250h','c',2020,'lexus_cpo').upper_man,350);
assert.equal(f('250h','c',2021,'general_market').median_man,353);
assert.equal(f('300h','fs',2024,'lexus_cpo').median_man,511.9);
assert.equal(f('300h','l',2024,'lexus_cpo').median_man,485.4);
assert.equal(f('300e','l',2021,'general_market').median_man,287.8);
assert.equal(f('200','fs',2019,'general_market').median_man,295.5);
assert.equal(f('200','base',2019,'general_market'),undefined);
assert.equal(f('250h','c',2025,'general_market'),undefined);
assert.equal(f('300h','fs',2025,'lexus_cpo'),undefined);
assert.equal(f('300e','l',2025,'general_market'),undefined);
assert(!html.includes('id="color"'));
console.log('UX_EXACT_GRADE_PRICE_TEST=PASS; cohorts='+json.cohorts.length);
