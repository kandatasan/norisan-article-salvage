const fs=require('fs'),vm=require('vm'),assert=require('assert');
const path=require('path'),root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/reference_price_bands.json'),'utf8'));
assert(!html.includes('全グレード'));
assert(!data.cohorts.some(c=>c.grade==='all'));
assert(html.includes('type="range" id="year"')&&html.includes('type="range" id="km"'));
assert(html.includes('id="price-range"'));
assert(!html.includes('id="general-price"')&&!html.includes('id="cpo-price"'));
assert(!html.includes('px.a8.net')&&!html.includes('ガリバー'));
const m=html.match(/function estimate\([^]*?\n\}(?=\nfunction render\(\))/);
assert(m,'approximate estimator missing');
const ctx={clamp:(v,min,max)=>Math.max(min,Math.min(max,v))};vm.createContext(ctx);vm.runInContext(m[0],ctx);
const est=(model,trim,y,km)=>ctx.estimate(model,trim,y,km,data.cohorts);
const base=est('250h','c',2021,30000);
assert(base&&base.gradeMatched===true&&base.cpoBased===false);
assert(base.low<base.high);
assert(est('250h','c',2022,30000).low>base.low,'year slider must affect result');
assert(est('250h','c',2021,90000).high<est('250h','c',2021,10000).high,'mileage slider must affect result');
const special=est('250h','emotional',2023,30000);
assert(special&&!special.gradeMatched,'unsupported trim must be clearly flagged as model-wide fallback');
const cpo=est('300h','l',2024,30000);
assert(cpo&&cpo.cpoBased&&cpo.gradeMatched);
assert(est('200','base',2019,30000)&&!est('200','base',2019,30000).gradeMatched);
assert(est('300e','l',2021,30000));
assert(est('250h','fs',2021,30000).high>est('250h','fs',2019,30000).high);
console.log('UX_ROUGH_PRICE_SLIDERS=PASS; verified_cohorts='+data.cohorts.length);
